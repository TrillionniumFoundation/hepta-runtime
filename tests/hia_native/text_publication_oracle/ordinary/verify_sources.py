def subset_lock(raw):
    text=raw.decode();blocks=text.split('[[package]]\n')
    entries={}
    for block in blocks[1:]:
        data=tomllib.loads('[[package]]\n'+block)['package'][0]
        if 'source' in data:entries[data['name'],data['version']]=(data,block)
    chosen=set();pending=list(DIRECT.items())
    while pending:
        key=pending.pop()
        if key in chosen:continue
        require(key in entries,'upstream dependency present')
        chosen.add(key)
        for dep in entries[key][0].get('dependencies',[]):
            words=dep.split();found=[k for k in entries if k[0]==words[0] and (len(words)==1 or k[1]==words[1])]
            require(len(found)==1,'unambiguous upstream dependency');pending.append(found[0])
    local='[[package]]\nname = "hepta-text-publication-original"\nversion = "0.1.0"\ndependencies = [\n'
    local+=''.join(' "'+name+'",\n' for name in sorted(DIRECT))+']\n\n'
    return ('# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n'+
        ''.join('[[package]]\n'+entries[key][1] for key in sorted(chosen))+local).encode()

