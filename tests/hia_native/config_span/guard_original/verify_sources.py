"""Extract byte-exact original guard/config projection and original lock subset."""
from pathlib import Path
import hashlib
import json
import tomllib

PINS = {'original/config.rs': '228f83aa263920ef16e6fca93ce52292cae3cecae5be4b47788a7070fee97f35',
        'original/runtime.Cargo.lock': '7f39704b92d5fc762a98a5313949034db464ca9485827b19b5dde7aa69902d43'}


def sha(raw): return hashlib.sha256(raw).hexdigest()


def assemble(root):
    root = Path(root); originals = {name: (root/name).read_bytes() for name in PINS}
    for name, digest in PINS.items(): assert sha(originals[name]) == digest, name
    raw = originals['original/config.rs']; spans = []; pieces = []
    def keep(name, start, end):
        part = raw[start:end]; pieces.append(part)
        spans.append({'name': name, 'file': 'original/config.rs', 'start': start, 'end': end, 'bytes': len(part), 'sha256': sha(part)})
    start = raw.index(b'static RUNTIME_CONFIG:'); keep('RUNTIME_CONFIG_declaration', start, raw.index(b'\n', start))
    for name, prefix in [('runtime_config', b'pub fn '), ('check_directory_move_against_roots', b'fn '), ('check_directory_move_source', b'pub fn ')]:
        start = raw.index(prefix+name.encode()+b'('); end = raw.index(b'\n}', start)+2; keep(name, start, end)
    driver = (root/'src/driver.rs').read_bytes(); assert driver.count(b'// ORIGINAL_DECLARATIONS') == 1
    main = driver.replace(b'// ORIGINAL_DECLARATIONS', b'\n\n'.join(pieces))
    packages = tomllib.loads(originals['original/runtime.Cargo.lock'].decode())['package']
    matches = [package for package in packages if package['name'] == 'anyhow' and package['version'] == '1.0.104']
    assert len(matches) == 1 and matches[0]['source'] == 'registry+https://github.com/rust-lang/crates.io-index' and not matches[0].get('dependencies')
    dependency = matches[0]
    lines = ['# This file is automatically @generated by Cargo.', '# It is not intended for manual editing.', 'version = 4', '', '[[package]]']
    lines += [key+' = '+json.dumps(dependency[key]) for key in ('name', 'version', 'source', 'checksum')]
    lines += ['', '[[package]]', 'name = "hepta-directory-guard-original"', 'version = "0.1.0"', 'dependencies = [', ' "anyhow",', ']', '']
    lock = '\n'.join(lines).encode()
    assert (root/'Cargo.lock').read_bytes() == lock, 'checked-in exact original lock subset'
    proof = {'schema': 'hepta.runtime.directory-move-guard-original-source.v1', 'unchanged_spans': spans,
        'original_files': {name: {'bytes': len(value), 'sha256': sha(value)} for name, value in originals.items()},
        'driver': {'bytes': len(driver), 'sha256': sha(driver)}, 'main': {'bytes': len(main), 'sha256': sha(main)},
        'cargo_lock': {'bytes': len(lock), 'sha256': sha(lock)}, 'registry_dependencies': 1,
        'unchanged_original_functions': 3, 'unchanged_original_static_declarations': 1,
        'std_canonicalize_is_actual': True, 'actual_empty_OnceLock_projection': True,
        'config_types_are_private_projection_holders': True, 'installed_config_startup_executed': False,
        'public_sdk_executed': False, 'public_filesystem_handler_executed': False, 'actual_move_executed': False}
    return main, lock, proof
