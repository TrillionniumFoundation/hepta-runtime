import argparse
import hashlib
import importlib.util
import json
import sys
import tomllib

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
TARGET_SHA = '38a2a860af8add7a1abc5fb14ac461b0060eb478e89e9e25d5f9ad309a8a2d4d'
TARGET_COMMIT = 'd3d75c30719db966b004756f610007a7c723729e'
TARGET_TREE = '612e145513961556ac8844b5cc978f9b5175e4d4'
HEADER = (b'// Copyright 2026 Muvon Un Limited\n'
          b'// Copyright 2026 TrillionniumFoundation\n'
          b'// SPDX-License-Identifier: Apache-2.0\n'
          b'// Exact production items; verified by the source extraction manifest.\n')
ADDITIONS = {
    'src/original_core.rs': ('src/mcp/fs/core.rs',
        b'\nuse super::super::McpToolCall;\nuse super::remote::{resolve_path_source, io_create_dir_all};\n'
        b'use crate::utils::line_hash::{self, Endpoint, resolve_line_index};\n'
        b'use crate::utils::truncation::format_extracted_content_smart;\nuse serde_json::Value;\n',
        ('fn parse_optional_endpoint(', 'pub async fn execute_extract_lines(')),
    'src/original_remote.rs': ('src/mcp/fs/remote.rs', b'\n',
        ('pub fn parse_path_source(', 'pub fn resolve_path_source(', 'pub async fn io_create_dir_all(')),
    'src/original_sftp_unavailable.rs': ('src/mcp/fs/remote_unavailable.rs', b'\n',
        ('pub async fn remote_create_dir_all(',)),
    'src/original_line_hash.rs': ('src/utils/line_hash.rs', b'\n',
        ('pub fn verify_line_id(', 'fn push_relocation(', 'pub(crate) fn resolve_line_index(',
         '#[derive(Debug, Clone, PartialEq, Eq)]\npub enum Endpoint', 'pub fn parse_endpoint(')),
    'src/original_truncation.rs': ('src/utils/truncation.rs', HEADER + b'use super::line_hash::line_id;\n',
        ('fn render_line(', 'pub fn format_extracted_content_smart(')),
    'src/original_mod.rs': ('src/mcp/mod.rs', HEADER +
        b'use serde::{Deserialize, Serialize};\nuse serde_json::Value;\nuse std::path::PathBuf;\n',
        ('#[derive(Debug, Clone, Serialize, Deserialize)]\npub struct McpToolCall',)),
}
REGISTRY_NAMES = ('anyhow', 'bytes', 'itoa', 'memchr', 'pin-project-lite', 'proc-macro2',
                  'quote', 'serde', 'serde_core', 'serde_derive', 'serde_json', 'syn',
                  'tokio', 'unicode-ident', 'zmij')


def identity(raw):
    return dict(bytes=len(raw), sha256=hashlib.sha256(raw).hexdigest(),
        git_blob=hashlib.sha1(b'blob ' + str(len(raw)).encode() + b'\0' + raw).hexdigest())


def dump(path, value):
    path.write_text(json.dumps(value, sort_keys=True, indent=2) + '\n')


def item(raw, declaration):
    token = declaration.encode()
    assert raw.count(token) == 1, declaration
    start = raw.index(token)
    assert start == 0 or raw[start - 1] == 10
    end = raw.index(b'\n}\n', start) + 3
    return start, end, raw[start:end]


def make_lock(target_raw):
    packages = tomllib.loads(target_raw.decode())['package']
    selected = {}
    for name in REGISTRY_NAMES:
        matches = [p for p in packages if p['name'] == name
                   and (name != 'syn' or p['version'] == '3.0.6')]
        assert len(matches) == 1, name
        selected[name] = matches[0]
    body = '# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n'
    project = dict(name='hepta-extract-lines-original-oracle', version='0.1.0',
                   dependencies=['anyhow', 'serde', 'serde_json', 'tokio'])
    for package in sorted([project, *selected.values()], key=lambda p: p['name']):
        body += '\n[[package]]\n'
        for key in ('name', 'version', 'source', 'checksum'):
            if key in package: body += key + ' = ' + json.dumps(package[key]) + '\n'
        deps = package.get('dependencies')
        if package['name'] == 'tokio': deps = ['bytes', 'pin-project-lite']
        if deps:
            deps = [name.removesuffix(' 3.0.6') if name == 'syn 3.0.6' else name for name in deps]
            assert all(name in selected for name in deps), (package['name'], deps)
            body += 'dependencies = [\n' + ''.join(' ' + json.dumps(name) + ',\n' for name in deps) + ']\n'
    return body.encode()


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--base', type=Path, required=True)
    p.add_argument('--output', type=Path, default=HERE)
    a = p.parse_args(); root = a.output.resolve(); reference = root / 'reference'
    metadata_raw = (reference / 'TARGET.json').read_bytes()
    assert hashlib.sha256(metadata_raw).hexdigest() == TARGET_SHA
    metadata = json.loads(metadata_raw)
    assert metadata['target_commit'] == TARGET_COMMIT and metadata['target_tree'] == TARGET_TREE
    targets = {}
    for name, expected in metadata['files'].items():
        raw = (reference / 'target' / name).read_bytes()
        assert identity(raw) == expected, name
        targets[name] = raw
    assert len(targets) == 12
    spec = importlib.util.spec_from_file_location('qualified_body_reference', a.base / 'verify_reference.py')
    verifier = importlib.util.module_from_spec(spec); spec.loader.exec_module(verifier)
    baseline = verifier.verify(a.base)
    assert baseline['exact_original_items'] == 74
    extraction_raw = (a.base / 'source-extraction.json').read_bytes()
    extraction = json.loads(extraction_raw)
    for name, row in extraction['source_files'].items():
        assert identity(targets[name]) == {k: row[k] for k in ('bytes', 'sha256', 'git_blob')}
    src = reference / 'src'; src.mkdir(exist_ok=False)
    units = {unit['path']: unit for unit in extraction['units']}
    for name in ('cache_observer.rs', 'history_observer.rs', 'lock_observer.rs'):
        (src / name).write_bytes((a.base / 'reference/src' / name).read_bytes())
    for name, unit in units.items():
        (reference / name).write_bytes((a.base / 'reference' / name).read_bytes())
    for name, (target, imports, declarations) in ADDITIONS.items():
        path = reference / name
        raw = path.read_bytes() if path.exists() else b''
        rows = list(units[name]['items']) if name in units else []
        raw += imports
        for declaration in declarations:
            start, end, original = item(targets[target], declaration)
            raw += b'\n'; included_start = len(raw); raw += original
            rows.append(dict(declaration=declaration, kind='brace_item', target=target,
                start=start, end=end, included_start=included_start, included_end=len(raw), **identity(original)))
        path.write_bytes(raw)
        units[name] = dict(path=name, items=rows, **identity(raw))
    (src / 'main.rs').write_bytes((root / 'reference_main.rs').read_bytes())
    cargo = ('[package]\nname = "hepta-extract-lines-original-oracle"\nversion = "0.1.0"\n'
        'edition = "2021"\nrust-version = "1.95"\n\n[dependencies]\nanyhow = "=1.0.104"\n'
        'serde = { version = "=1.0.229", features = ["derive"] }\n'
        'serde_json = { version = "=1.0.151", features = ["float_roundtrip", "raw_value"] }\n'
        'tokio = { version = "=1.53.3", features = ["rt", "fs", "io-util", "sync"] }\n'
        '\n[features]\nremote-fs = []\n\n[workspace]\n').encode()
    (reference / 'Cargo.toml').write_bytes(cargo)
    (reference / 'Cargo.lock').write_bytes(make_lock(targets['Cargo.lock']))
    manifest = dict(schema='hepta.runtime.extract-lines-original-extraction.v1',
        target_commit=TARGET_COMMIT, target_tree=TARGET_TREE, target_metadata=identity(metadata_raw),
        source_files=metadata['files'], base_extraction=identity(extraction_raw),
        base_verified=baseline, units=[units[name] for name in sorted(units)],
        exact_original_items=sum(len(unit['items']) for unit in units.values()),
        cargo={name:identity((reference/name).read_bytes()) for name in ('Cargo.toml','Cargo.lock')},
        fixture_files={str(path.relative_to(reference)):identity(path.read_bytes())
            for path in sorted(src.iterdir()) if path.is_file()},
        original_items_unchanged=True, fresh_original_build=False, original_executed=False,
        private_local_body_only=True, remote_qualified=False, public_handler_qualified=False)
    dump(root / 'reference-source.json', manifest)
    (root / 'reference-base-extraction.json').write_bytes(extraction_raw)
    print(json.dumps({k:manifest[k] for k in ('schema','exact_original_items','target_commit','fresh_original_build')}))


if __name__ == '__main__': main()
