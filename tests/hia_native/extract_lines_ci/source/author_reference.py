#!/usr/bin/env python3
"""Extract the unchanged Local extract body and its real original dependencies.

This source-only author never invokes Rust or substitutes a production routine.
The already-qualified 74-item Local text body extraction is retained verbatim;
new items are copied from the twelve whole, Git-bound target files.
"""
